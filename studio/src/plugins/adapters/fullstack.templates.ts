import { VERSION, type UiProjectDefinition } from '@chronos-ui/svelte';

export function buildVendoredPackageJson(project: UiProjectDefinition): string {
	return JSON.stringify({
		name: `${project.slug}-fullstack`,
		version: '1.0.0',
		private: true,
		type: 'module',
		description: `Standalone full-stack app generated by @chronos-ui/svelte v${VERSION}`,
		scripts: {
			dev: 'bun --watch server/index.ts',
			start: 'bun run server/index.ts',
			'db:migrate': 'bun run server/migrate.ts',
			health: 'curl -fsS http://localhost:3000/api/health'
		},
		dependencies: { 'drizzle-orm': '^0.45.4' }
	}, null, '\t');
}

export function buildVendoredEnvAndDrizzle(project: UiProjectDefinition): { envExample: string; drizzleConfig: string; readme: string } {
	const envExample = ['PORT=3000', 'DB_FILE_NAME=./data/app.sqlite', 'CORS_ORIGIN=http://localhost:3000', 'APP_API_SECRET=replace-me-before-production', ''].join('\n');
	const drizzleConfig = `import { defineConfig } from 'drizzle-kit';\nexport default defineConfig({ out: './drizzle', schema: './server/schema.ts', dialect: 'sqlite', dbCredentials: { url: process.env.DB_FILE_NAME ?? './data/app.sqlite' } });\n`;
	const readme = [`# ${project.name} — Standalone Full-Stack Bundle`, '', 'Self-contained Bun + Drizzle SQLite + optimized static client exported from Chronos UI Studio.', '', '## Quickstart (2 Commands)', '', '1. Install minimal dependencies: bun install', '2. Boot migrations and HTTP server: bun run start', ''].join('\n');
	return { envExample, drizzleConfig, readme };
}

export function buildVendoredSqlMigration(project: UiProjectDefinition): { sql: string; journal: string } {
	const includeCursors = Boolean(project.activeCursorPackId);
	const stmts = [
		'CREATE TABLE IF NOT EXISTS app_meta (key TEXT PRIMARY KEY NOT NULL, value TEXT NOT NULL, updated_at INTEGER NOT NULL);',
		'CREATE TABLE IF NOT EXISTS ui_entities (uuid TEXT PRIMARY KEY NOT NULL, zone_id TEXT NOT NULL, kind TEXT NOT NULL, label TEXT NOT NULL, shape TEXT NOT NULL, locked INTEGER NOT NULL DEFAULT 0, visible INTEGER NOT NULL DEFAULT 1, props_json TEXT NOT NULL, updated_at INTEGER NOT NULL);',
		'CREATE TABLE IF NOT EXISTS ui_revisions (id TEXT PRIMARY KEY NOT NULL, actor TEXT NOT NULL, payload_json TEXT NOT NULL, created_at INTEGER NOT NULL);',
		'CREATE TABLE IF NOT EXISTS app_events (id INTEGER PRIMARY KEY AUTOINCREMENT, kind TEXT NOT NULL, payload_json TEXT NOT NULL, created_at INTEGER NOT NULL);',
		...(includeCursors ? ['CREATE TABLE IF NOT EXISTS cursor_packs (uuid TEXT PRIMARY KEY NOT NULL, name TEXT NOT NULL, css_text TEXT NOT NULL, updated_at INTEGER NOT NULL);'] : [])
	];
	const journal = JSON.stringify({ version: '7', dialect: 'sqlite', entries: [{ idx: 0, version: '6', when: Date.now(), tag: '0000_init', breakpoints: true }] }, null, '\t');
	return { sql: `${stmts.join('\n')}\n`, journal };
}

function buildVendoredDbFiles(project: UiProjectDefinition): Record<string, string> {
	const seedEntities = project.nodes.map((n) => ({ uuid: n.id, zoneId: n.zone, kind: n.type, label: n.label, shape: n.shape ?? 'BOX', locked: n.locked ? 1 : 0, visible: n.visible === false ? 0 : 1, propsJson: JSON.stringify(n.props ?? {}), updatedAt: Date.now() }));
	const schemaTs = [
		`import { integer, sqliteTable, text } from 'drizzle-orm/sqlite-core';`,
		`export const appMeta = sqliteTable('app_meta', { key: text('key').primaryKey(), value: text('value').notNull(), updatedAt: integer('updated_at').notNull() });`,
		`export const uiEntities = sqliteTable('ui_entities', { uuid: text('uuid').primaryKey(), zoneId: text('zone_id').notNull(), kind: text('kind').notNull(), label: text('label').notNull(), shape: text('shape').notNull(), locked: integer('locked').notNull().default(0), visible: integer('visible').notNull().default(1), propsJson: text('props_json').notNull(), updatedAt: integer('updated_at').notNull() });`,
		`export const uiRevisions = sqliteTable('ui_revisions', { id: text('id').primaryKey(), actor: text('actor').notNull(), payloadJson: text('payload_json').notNull(), createdAt: integer('created_at').notNull() });`,
		`export const appEvents = sqliteTable('app_events', { id: integer('id').primaryKey({ autoIncrement: true }), kind: text('kind').notNull(), payloadJson: text('payload_json').notNull(), createdAt: integer('created_at').notNull() });`, ''
	].join('\n');
	const dbTs = [
		`import { Database } from 'bun:sqlite';`, `import { drizzle } from 'drizzle-orm/bun-sqlite';`,
		`import { mkdirSync } from 'node:fs';`, `import { dirname } from 'node:path';`, `import * as schema from './schema';`,
		`export function openAppDb(filePath = process.env.DB_FILE_NAME ?? './data/app.sqlite') {`,
		`\tif (filePath !== ':memory:') mkdirSync(dirname(filePath), { recursive: true });`,
		`\tconst sqlite = new Database(filePath); sqlite.exec('PRAGMA journal_mode = WAL; PRAGMA foreign_keys = ON;');`,
		`\treturn { sqlite, db: drizzle(sqlite, { schema }) };`, `}`, ''
	].join('\n');
	const migrateTs = [
		`import { readFileSync } from 'node:fs';`, `import { join } from 'node:path';`,
		`import { openAppDb } from './db';`, `import { appMeta, uiEntities } from './schema';`,
		`const SEED_META = ${JSON.stringify({ id: project.id, slug: project.slug, name: project.name, themeId: project.themeId, cornerMode: project.cornerMode })};`,
		`const SEED_ENTITIES = ${JSON.stringify(seedEntities)};`,
		`export async function runMigrations(filePath = process.env.DB_FILE_NAME ?? './data/app.sqlite') {`,
		`\tconst conn = openAppDb(filePath); conn.sqlite.exec(readFileSync(join(import.meta.dir, '../drizzle/0000_init.sql'), 'utf8'));`,
		`\tif ((await conn.db.select().from(appMeta).limit(1)).length === 0) {`,
		`\t\tawait conn.db.insert(appMeta).values({ key: 'project', value: JSON.stringify(SEED_META), updatedAt: Date.now() });`,
		`\t\tfor (const e of SEED_ENTITIES) await conn.db.insert(uiEntities).values(e).onConflictDoNothing();`,
		`\t}`,
		`\treturn conn;`, `}`,
		`if (import.meta.main) { await runMigrations(); console.log('[db:migrate] Applied 0000_init.sql cleanly.'); }`, ''
	].join('\n');
	return { 'server/schema.ts': schemaTs, 'server/db.ts': dbTs, 'server/migrate.ts': migrateTs };
}

function buildVendoredRouterFiles(project: UiProjectDefinition): Record<string, string> {
	const routerTs = [
		`import { existsSync } from 'node:fs';`, `import { join, normalize } from 'node:path';`,
		`import type { openAppDb } from './db';`, `import { appEvents, appMeta, uiEntities } from './schema';`,
		`export function createAppHandler(conn: ReturnType<typeof openAppDb>, clientDir = join(import.meta.dir, '../client')) {`,
		`\treturn async (req: Request): Promise<Response> => {`,
		`\t\tconst url = new URL(req.url);`,
		`\t\tif (url.pathname === '/api/health') return Response.json({ ok: true, status: 'healthy', service: ${JSON.stringify(project.slug)} });`,
		`\t\tif (url.pathname === '/api/project') { const rows = await conn.db.select().from(appMeta).limit(1); return Response.json({ project: rows[0] ? JSON.parse(rows[0].value) : null }); }`,
		`\t\tif (url.pathname === '/api/entities' && req.method === 'POST') {`,
		`\t\t\tconst body = await req.json() as { uuid?: string; type?: string; kind?: string; zone?: string; zoneId?: string; label?: string; shape?: string; props?: Record<string, unknown> };`,
		`\t\t\tconst row = { uuid: body.uuid ?? crypto.randomUUID(), zoneId: String(body.zoneId ?? body.zone ?? 'WORLD_CANVAS'), kind: String(body.kind ?? body.type ?? 'UiChamferFrame'), label: String(body.label ?? 'Entity'), shape: String(body.shape ?? 'BOX'), locked: 0, visible: 1, propsJson: JSON.stringify(body.props ?? {}), updatedAt: Date.now() };`,
		`\t\t\tawait conn.db.insert(uiEntities).values(row).onConflictDoNothing();`,
		`\t\t\treturn Response.json({ ok: true, entity: row }, { status: 201 });`,
		`\t\t}`,
		`\t\tif (url.pathname === '/api/entities') return Response.json({ entities: await conn.db.select().from(uiEntities) });`,
		`\t\tif (url.pathname === '/api/events' && req.method === 'POST') { const body = await req.json() as { kind?: string; payload?: unknown }; await conn.db.insert(appEvents).values({ kind: String(body.kind ?? 'APP_EVENT'), payloadJson: JSON.stringify(body.payload ?? {}), createdAt: Date.now() }); return Response.json({ ok: true }, { status: 201 }); }`,
		`\t\tif (url.pathname === '/api/mcp') return Response.json({ jsonrpc: '2.0', result: { tools: ['get_ui_structure', 'list_entities', 'get_theme_tokens'] } });`,
		`\t\tconst rel = normalize(url.pathname === '/' ? 'index.html' : url.pathname.replace(/^\\/+/, ''));`,
		`\t\tconst filePath = join(clientDir, rel);`,
		`\t\tif (!rel.startsWith('..') && existsSync(filePath)) return new Response(Bun.file(filePath), { headers: { 'Cache-Control': rel.startsWith('assets/') ? 'public, max-age=31536000, immutable' : 'no-cache' } });`,
		`\t\treturn new Response(Bun.file(join(clientDir, 'index.html')), { headers: { 'Cache-Control': 'no-cache' } });`,
		`\t};`, `}`, ''
	].join('\n');
	const indexTs = [
		`import { runMigrations } from './migrate';`, `import { createAppHandler } from './router';`,
		`const port = Number(process.env.PORT ?? 3000);`, `const conn = await runMigrations();`,
		`Bun.serve({ port, fetch: createAppHandler(conn) });`,
		`console.log(\`[${project.slug}] Full-stack server running on http://localhost:\${port}\`);`, ''
	].join('\n');
	return { 'server/router.ts': routerTs, 'server/index.ts': indexTs };
}

export function buildVendoredServerFiles(project: UiProjectDefinition): Record<string, string> {
	return { ...buildVendoredDbFiles(project), ...buildVendoredRouterFiles(project) };
}
