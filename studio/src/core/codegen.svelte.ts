import { findThemePack, VERSION } from '@chronos-ui/svelte';
import type { UiBlueprint } from '../config';

export function generateSvelteScaffold(bp: UiBlueprint): string {
	const hidden = bp.zones.filter((z) => !z.visible).map((z) => `'${z.id}'`).join(', ');
	const lines = [
		`<script lang="ts">`,
		`\t// Generated by @chronos-ui/svelte v${VERSION} Builder Studio`,
		`\timport {`,
		`\t\tUiPerimeterHud,`,
		`\t\tUiChamferFrame,`,
		`\t\tUiInteractiveCanvasStage,`,
		`\t\tapplyThemeToRoot,`,
		`\t\tfindThemePack,`,
		`\t\ttype HudZoneId`,
		`\t} from '@chronos-ui/svelte';`,
		`\tconst hiddenZones = new Set<HudZoneId>([${hidden}]);`,
		`\tlet panX = $state(0);`,
		`\tlet panY = $state(0);`,
		`\tlet zoom = $state(1);`,
		`\t$effect(() => { applyThemeToRoot(findThemePack('${bp.themeId}')); });`,
		`<\/script>`,
		`<UiPerimeterHud {hiddenZones} cornerMode="${bp.cornerMode}">`,
		`\t{#snippet worldCanvas()}`,
		`\t\t<UiInteractiveCanvasStage {panX} {panY} {zoom} cornerMode="${bp.cornerMode}"`,
		`\t\t\tonPanDelta={(dx, dy) => { panX += dx; panY += dy; }}`,
		`\t\t\tonZoomDelta={(d) => { zoom = Math.max(0.4, Math.min(2.2, zoom + d)); }}>`,
		`\t\t\t<div class="p-8 text-center"><h1>${bp.name}</h1></div>`,
		`\t\t</UiInteractiveCanvasStage>`,
		`\t{/snippet}`,
		`\t{#snippet topLeft()}`,
		`\t\t<UiChamferFrame cornerMode="${bp.cornerMode}" className="h-full p-3">${bp.name}</UiChamferFrame>`,
		`\t{/snippet}`,
		`</UiPerimeterHud>`
	];
	return lines.join('\n');
}

export function generateCssTokenSheet(themeId: string): string {
	const pack = findThemePack(themeId);
	const entries = Object.entries(pack.tokens)
		.map(([k, v]) => `\t${k}: ${v};`)
		.join('\n');
	return `:root[data-ui-theme="${pack.id}"][data-ui-polarity="${pack.polarity}"] {\n${entries}\n}\n`;
}
